namespace Mason.Geometry;

/// <summary>
/// Represents a 3D Cartesian axis.
/// </summary>
public enum Axis
{
    /// <summary>
    /// The X-axis (horizontal direction).
    /// </summary>
    X = 0,

    /// <summary>
    /// The Y-axis (vertical or lateral direction).
    /// </summary>
    Y = 1,

    /// <summary>
    /// The Z-axis (upward direction).
    /// </summary>
    Z = 2,
}
